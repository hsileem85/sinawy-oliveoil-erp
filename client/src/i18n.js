export function t(lang, key) {
  return translations[lang]?.[key] || translations.en[key] || key;
}

export function formatEGP(amount, lang = 'en') {
  const num = Number(amount || 0);
  const formatted = new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', {
    minimumFractionDigits: 0,
    maximumFractionDigits: 2,
  }).format(num);
  return lang === 'ar' ? `${formatted} ج.م` : `EGP ${formatted}`;
}

export function formatNum(num, decimals = 2) {
  return new Intl.NumberFormat('en-US', {
    minimumFractionDigits: 0,
    maximumFractionDigits: decimals,
  }).format(Number(num || 0));
}

export function pickName(item, lang, field = 'name') {
  if (!item) return '';
  if (lang === 'ar' && item[`${field}_ar`]) return item[`${field}_ar`];
  return item[field] || '';
}
